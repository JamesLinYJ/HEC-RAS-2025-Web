export function editorText(language: Language, source: string): string {
  if (language !== 'zh') return source;
  const direct = labels[source];
  if (direct) return direct;
  const gpuDevicePrefix = 'Use the explicit GPU solver with device: ';
  if (source.startsWith(gpuDevicePrefix)) {
    return `使用显式 GPU 求解器，设备：${source.slice(gpuDevicePrefix.length)}`;
  }
  return source;
}

export function editorAssetKind(language: Language, kind: string): string {
  return language === 'zh' ? assetKinds[kind] ?? editorText(language, kind) : kind;
}

export function editorValueLabel(language: Language, value: string): string {
  return language === 'zh' ? valueLabels[value] ?? editorText(language, value) : value;
}

export function editorPageTitle(pageID: string, language: Language): string {
  const entry = pageTitles[pageID];
  if (entry) return entry[language === 'zh' ? 0 : 1];
  const spaced = pageID.replace(/([a-z])([A-Z])/g, '$1 $2');
  return editorText(language, spaced);
}

export function editorTableTitle(language: Language, tableID: string): string {
  const leaf = tableID.split('/').at(-1) ?? tableID;
  if (language === 'en') return leaf.replace(/([a-z])([A-Z])/g, '$1 $2');
  const tableTitles: Record<string, string> = {
    Values: '数值', Stations: '测站坐标', InterpretationTable: '糙率解释表',
    Interpretation: '解释表', ManningValues: '糙率值', Elevation: '高程',
  };
  return tableTitles[leaf] ?? editorText(language, leaf.replace(/([a-z])([A-Z])/g, '$1 $2'));
}
